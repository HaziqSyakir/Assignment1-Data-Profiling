# Detect outliers using IQR method

numerical_cols = ['Age', 'CreditAmount', 'Duration']

outlier_summary = []

for col in numerical_cols:
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    outliers = df[
        (df[col] < lower_bound) |
        (df[col] > upper_bound)
    ]

    outlier_summary.append({
        'Feature': col,
        'Lower Bound': lower_bound,
        'Upper Bound': upper_bound,
        'Outlier Count': len(outliers),
        'Outlier Percentage (%)': round(
            len(outliers) / len(df) * 100, 2
        )
    })

outlier_df = pd.DataFrame(outlier_summary)

print("Outlier Detection Summary:")
display(outlier_df)

# Keep the existing IQR detection cell before this cell.
numerical_cols = ["Age", "CreditAmount", "Duration"]

# Preserve row-level evidence of statistical outliers.
outlier_flags = pd.DataFrame(index=df.index)

for col in numerical_cols:
    q1 = df[col].quantile(0.25)
    q3 = df[col].quantile(0.75)
    iqr = q3 - q1

    outlier_flags[f"{col}_IQR_flag"] = (
        (df[col] < q1 - 1.5 * iqr)
        | (df[col] > q3 + 1.5 * iqr)
    )

# Retain original records and values; add three audit columns.
df_cleaned = df.copy().join(outlier_flags)
any_outlier = outlier_flags.any(axis=1)

print("Observed numerical ranges:")
display(df[numerical_cols].agg(["min", "max"]).T)

print("Outlier counts by feature:")
display(outlier_flags.sum().to_frame("Flagged Records"))

print("Distinct records with at least one flag:", int(any_outlier.sum()))
